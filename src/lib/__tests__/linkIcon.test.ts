/**
 * linkIcon.ts unit tests (vitest, node environment via vitest.config.lib.ts).
 *
 * Covers:
 *   1. iconForType() returns correct Icon + color for known types.
 *   2. iconForType() falls back to 'web' for unknown/null/undefined.
 *   3. ICONS_HASH === PB contract hash (cross-repo drift gate).
 *
 * Run: npx vitest run --config vitest.config.lib.ts
 */

import { describe, it, expect } from 'vitest'
import { iconForType, dimLinkColor, ICONS_HASH } from '../linkIcon'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { PencilLine, Globe } from 'lucide-react'

// PB contract hash — generated by gen_links.py and embedded in
// pbLinkIcons.generated.ts. If this assertion fails, the Hub icon map has
// drifted from the PB link_contract.py source of truth.
// Regenerate: cd ~/Peripheral-Brain && python -X utf8 scripts/links/gen_links.py
const PB_CONTRACT_HASH = 'ff69496c9230775019b163d7b1cb79d0d87e02c8232c9b027a481078f6e7b2f8'

describe('iconForType', () => {
  it('returns PencilLine for gmail_draft with Gmail red token', () => {
    const { Icon, color } = iconForType('gmail_draft')
    expect(Icon).toBe(PencilLine)
    expect(color).toBe('var(--link-gmail-draft)')
  })

  it('returns Globe for unknown type (fallback to web)', () => {
    const { Icon, color } = iconForType('???')
    expect(Icon).toBe(Globe)
    expect(color).toBe('var(--link-web)')
  })

  it('returns Globe for null (fallback to web)', () => {
    const { Icon } = iconForType(null)
    expect(Icon).toBe(Globe)
  })

  it('returns Globe for undefined (fallback to web)', () => {
    const { Icon } = iconForType(undefined)
    expect(Icon).toBe(Globe)
  })

  it('returns correct Icon for all 16 known types', () => {
    const types = [
      'google_doc', 'google_sheet', 'google_slide', 'google_form',
      'box_folder', 'github_repo', 'github_issue', 'github_tree',
      'gmail_thread', 'gmail_draft', 'obsidian_note',
      'local_folder', 'local_file', 'web', 'artifact', 'iwd',
    ]
    for (const t of types) {
      const spec = iconForType(t)
      expect(spec.Icon, `Icon for ${t} should be defined`).toBeDefined()
      expect(spec.color, `color for ${t} should be a CSS var`).toMatch(/^var\(--link-/)
    }
  })
})

// Color back pick 9 (Nick 2026-10-11): link icons keep their own brand colors,
// dimmer. Every glyph paints `tint`, the brand token mixed toward the gray
// ramp at ONE strength, --link-strength, which the Today skin's [data-lk]
// icons read too.
describe('link icon tint (same colors, dimmer)', () => {
  const css = readFileSync(resolve(__dirname, '../../index.css'), 'utf-8')

  it('tint is the brand token mixed at --link-strength toward gray', () => {
    for (const t of ['gmail_thread', 'google_sheet', 'google_doc', 'artifact', '???']) {
      const { color, tint } = iconForType(t)
      expect(tint).toBe(dimLinkColor(color))
      expect(tint).toBe(`color-mix(in srgb, ${color} var(--lk-on, var(--link-strength)), var(--sk-t3))`)
    }
  })

  it('index.css sets one strength below 100% and the Today skin reads it', () => {
    const m = css.match(/--link-strength:\s*(\d+)%/)
    expect(m).not.toBeNull()
    const pct = Number(m![1])
    expect(pct).toBeGreaterThan(30)
    expect(pct).toBeLessThan(70) // dimmer than the Today skin's old 70%
    const todayMixes = css.match(/color-mix\(in srgb,var\(--lk\) [^,]+,/g) ?? []
    expect(todayMixes.length).toBeGreaterThanOrEqual(2)
    for (const mix of todayMixes) expect(mix).toContain('var(--link-strength)')
  })
})

describe('ICONS_HASH cross-repo drift gate', () => {
  it('matches the PB contract hash (pbLinkIcons.generated.ts)', () => {
    expect(ICONS_HASH).toBe(PB_CONTRACT_HASH)
  })
})
